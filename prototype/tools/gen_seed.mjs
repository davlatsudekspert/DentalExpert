// Generates migrations/0002_demo_seed.sql from src/discoveryData.ts. Demo rows are flagged is_demo=1.
import {build} from 'esbuild';
import {writeFileSync} from 'node:fs';
const out=await build({entryPoints:['src/discoveryData.ts'],bundle:true,format:'esm',write:false});
const mod=await import('data:text/javascript;base64,'+Buffer.from(out.outputFiles[0].text).toString('base64'));
const q=v=>v==null?'NULL':typeof v==='number'?String(v):"'"+String(v).replace(/'/g,"''")+"'";
const j=v=>q(JSON.stringify(v));
const rows=[];
const countries={UZ:{uz:'O‘zbekiston',ru:'Узбекистан',en:'Uzbekistan'},AE:{uz:'Birlashgan Arab Amirliklari',ru:'ОАЭ',en:'United Arab Emirates'}};
for(const [c,n] of Object.entries(countries))rows.push(`INSERT INTO countries (code,name) VALUES (${q(c)},${j(n)});`);
for(const c of mod.demoCities)rows.push(`INSERT INTO cities (id,country_code,name) VALUES (${q(c.id)},${q(c.countryCode)},${j(c.label)});`);
for(const d of mod.demoDoctors){
 const clinicId='clinic-'+d.id;
 rows.push(`INSERT INTO clinicians (id,full_name,initials,specialty,bio,languages,services,years,license_status,is_demo) VALUES (${q(d.id)},${q(d.name)},${q(d.initials)},${j(d.specialty)},${j(d.bio)},${j(d.languages)},${j(d.services)},${d.years},'unverified',1);`);
 rows.push(`INSERT INTO clinics (id,name,city_id,address,is_demo) VALUES (${q(clinicId)},${q(d.clinic)},${q(d.cityId)},${j(d.address)},1);`);
 rows.push(`INSERT INTO clinician_clinics (clinician_id,clinic_id) VALUES (${q(d.id)},${q(clinicId)});`);
}
writeFileSync('migrations/0002_demo_seed.sql','-- Generated by tools/gen_seed.mjs. All rows are fictional demo data (is_demo=1), no contacts.\n'+rows.join('\n')+'\n');
console.log(rows.length,'statements');
