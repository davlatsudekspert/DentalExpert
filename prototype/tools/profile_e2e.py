"""Dentist signs in: sees their own name, edits and saves the profile for real, adds a patient, marks teeth, data survives reload."""
from playwright.sync_api import sync_playwright
import os,json,time
BASE='http://127.0.0.1:8788';OUT=os.environ.get('SIM_OUT','/tmp/sim')
def check(n,c):print(('PASS ' if c else 'FAIL ')+n);assert c,n
with sync_playwright() as p:
    b=p.chromium.launch(executable_path=os.environ['CHROMIUM_PATH'],args=['--no-sandbox'])
    ctx=b.new_context(viewport={'width':430,'height':932},device_scale_factor=2,is_mobile=True,has_touch=True)
    e=f'dentist+{time.time_ns()}@example.com'
    post=lambda path,body:ctx.request.post(BASE+path,data=json.dumps(body),headers={'content-type':'application/json'})
    r=post('/api/auth/request-code',{'email':e,'name':'Ali Abduraxmon','role':'dentist','lang':'uz'}).json()
    post('/api/auth/verify',{'email':e,'code':r['devCode']})
    pg=ctx.new_page();errs=[];pg.on('pageerror',lambda x:errs.append(str(x)))
    pg.goto(BASE+'/?lang=uz');pg.wait_for_selector('.home-header');pg.wait_for_timeout(800)
    txt=pg.inner_text('.phone')
    check('dashboard greets the real user',('Ali Abduraxmon' in txt) and 'Kamila' not in txt and 'Aziza' not in txt and 'Jasur' not in txt)
    check('initials are AA',pg.locator('.home-header .avatar').inner_text()=='AA')
    pg.screenshot(path=OUT+'/p1-dashboard.png')
    pg.goto(BASE+'/?screen=edit&lang=uz');pg.wait_for_selector('.profile-form');pg.wait_for_timeout(500)
    pg.locator('.profile-form').get_by_label('Telefon',exact=True).fill('+998 90 123 45 67');pg.locator('.profile-form').get_by_label('Ish joyi',exact=True).fill('Smile Clinic');pg.locator('.profile-form').get_by_label('O‘zingiz haqingizda').fill('Ortodont, 8 yil tajriba')
    pg.locator('.profile-form').get_by_label('Telegram foydalanuvchi nomi').fill('@drtest');pg.locator('.profile-form').get_by_label('Aloqa uchun email (ochiq)').fill('dr@example.com');pg.locator('form button[type=submit]').click()
    pg.wait_for_timeout(800)
    me=ctx.request.get(BASE+'/api/auth/me').json()['user']
    check('profile saved on the server',me['phone']=='+998 90 123 45 67' and me['workplace']=='Smile Clinic' and me['bio'].startswith('Ortodont') and me['telegram']=='@drtest' and me['publicEmail']=='dr@example.com')
    check('bad phone rejected',ctx.request.put(BASE+'/api/auth/profile',data=json.dumps({'name':'Ali','phone':'abc'}),headers={'content-type':'application/json'}).status==400)
    check('anonymous cannot edit profile',b.new_context().request.put(BASE+'/api/auth/profile',data=json.dumps({'name':'X Y'}),headers={'content-type':'application/json'}).status==401)
    pg.goto(BASE+'/?lang=uz');pg.wait_for_selector('.home-header');pg.wait_for_timeout(600)
    check('profile banner gone at 100%',pg.locator('.dash-banner').count()==0)
    pg.goto(BASE+'/?screen=record&lang=uz');pg.wait_for_selector('.patients');pg.wait_for_timeout(300)
    pg.get_by_role('button',name='Bemor qo‘shish').click();pg.get_by_label('Ism va familiya').fill('Test Bemor');pg.get_by_label('Telefon',exact=True).fill('+998 91 000 00 00')
    pg.get_by_role('button',name='Saqlash').click();pg.wait_for_timeout(400)
    pg.locator('.pt-tooth').first.click();pg.get_by_role('button',name='Karies').click()
    pg.locator('.pt-tooth').nth(5).click();pg.get_by_role('button',name='Plomba').click()
    pg.locator('input[placeholder="Nima qilindi?"]').fill('Karies davolandi');pg.get_by_role('button',name='Qabul qaydini qo‘shish').click();pg.wait_for_timeout(300)
    pg.screenshot(path=OUT+'/p2-odontogram.png',full_page=True)
    pg.reload();pg.wait_for_selector('.patients');pg.get_by_role('button',name='Test Bemor').click();pg.wait_for_timeout(300)
    check('tooth states persisted',pg.locator('.pt-tooth').first.get_attribute('aria-label').endswith('Karies') and pg.locator('.pt-tooth').nth(5).get_attribute('aria-label').endswith('Plomba'))
    check('visit persisted',pg.get_by_text('Karies davolandi').count()==1)
    pg.goto(BASE+'/?lang=uz');pg.wait_for_selector('.home-header');pg.wait_for_timeout(500)
    check('dashboard shows 1 patient',pg.get_by_text('Test Bemor').count()==1)
    pg.screenshot(path=OUT+'/p3-dashboard-after.png')
    check('no page errors',not errs)
    b.close()
print('PROFILE E2E OK')
