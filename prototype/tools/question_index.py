"""Server copy of the deck (presentation) quiz keys, for the one question index (functions/_lib/questionIndex.ts):
python3 tools/question_index.py writes functions/_lib/deckKeys.ts from public/decks/manifest.<lang>.json;
--check only verifies the file is up to date and that the three languages agree on keys and option counts.
(Topic-test keys come from tools/curriculum.py build → functions/_lib/curriculumKeys.ts.)"""
import json,os,sys
ROOT=os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT=os.path.join(ROOT,'functions','_lib','deckKeys.ts')
LANGS=('uz','ru','en')
def build():
    m={l:{d['id']:d for d in json.load(open(os.path.join(ROOT,'public','decks',f'manifest.{l}.json'),encoding='utf-8'))} for l in LANGS}
    ids=list(m['uz'])
    assert all(set(m[l])==set(ids) for l in LANGS),'decks differ between languages'
    out={}
    for i in ids:
        qs={l:m[l][i].get('quiz',[]) for l in LANGS}
        n=len(qs['uz']);assert all(len(qs[l])==n for l in LANGS),f'{i}: quiz length differs'
        c=[q['correct'] for q in qs['uz']]
        for l in LANGS:
            for k,q in enumerate(qs[l]):
                assert q['correct']==c[k] and len(q['options'])==len(qs['uz'][k]['options']) and 0<=q['correct']<len(q['options']),f'{i}#{k} {l}: key or options differ'
        out[i]={'c':c,'e':[{l:qs[l][k].get('explanation','') for l in ('en','ru','uz')} for k in range(n)]}
    return ('// Generated by tools/question_index.py — do not edit. Deck quiz keys for server-side scoring.\n'
            'type L={en:string;ru:string;uz:string};\n'
            'export const DECK_KEYS:Record<string,{c:number[];e:L[]}>='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
if __name__=='__main__':
    ts=build()
    if '--check' in sys.argv:
        assert os.path.exists(OUT) and open(OUT,encoding='utf-8').read()==ts,'functions/_lib/deckKeys.ts is out of date: run python3 tools/question_index.py'
        print('deck keys up to date')
    else:
        open(OUT,'w',encoding='utf-8').write(ts);print('wrote',OUT)
