def build():
    return {'note':'Generated by tools/variant_vectors.py (independent Python implementation). expected = indices into pool, in display order.',
     'sha256':[{'input':s,'hex':h(s)} for s in ['', 'abc', 'a1:u1:card-01:0', 'Gʻayrat ўзбек']],
     'cases':[{'name':n,'assignmentId':a,'userId':u,'pool':p,'count':c,'primary':pr,'expected':draw(a,u,p,c,pr)} for n,a,u,p,c,pr in CASES]}

if __name__=='__main__':
    data=build()
    if '--check' in sys.argv:
        old=json.load(open(OUT,encoding='utf-8'))
        assert old==data,'tools/variant_vectors.json is out of date: run python3 tools/variant_vectors.py'
        # The rules the vectors encode, so a wrong change to both implementations still fails here.
        for c in data['cases']:
            e=c['expected'];n=max(0,min(c['count'],len(c['pool'])))
            assert len(e)==n and len(set(e))==n,c['name']
        print(f"variant vectors OK ({len(data['cases'])} cases)")
    else:
        with open(OUT,'w',encoding='utf-8') as f:json.dump(data,f,ensure_ascii=False,indent=1);f.write('\n')
        print('wrote',OUT)
