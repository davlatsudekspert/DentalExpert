"""Independent Python implementation of the per-student variant draw (src/classroomShared.ts drawVariant) and the shared
test vectors. `python3 tools/variant_vectors.py` rewrites tools/variant_vectors.json; `--check` only verifies that the
file matches this implementation. tools/variant_test.ts checks the TypeScript draw (used by the server and the app)
against the same file, and tools/classroom_v2_test.py checks the live server's draws with draw() below."""
import hashlib,json,math,os,sys
HERE=os.path.dirname(os.path.abspath(__file__))
OUT=os.path.join(HERE,'variant_vectors.json')

def h(s):return hashlib.sha256(s.encode('utf-8')).hexdigest()
def topic(ref):return ref[:ref.rindex(':')]

def draw(assignment_id,user_id,pool,count,primary=None):
    seed=f'{assignment_id}:{user_id}'
    hs=[h(f'{seed}:{r}') for r in pool]
    strata={}
    for i,r in enumerate(pool):strata.setdefault(topic(r),[]).append(i)
    for s in strata.values():s.sort(key=lambda i:(hs[i],pool[i]))
    n=max(0,min(int(count),len(pool)))
    use_primary=bool(primary) and primary in strata and len(strata)>1
    P=strata[primary] if use_primary else []
    out=[];taken=0
    if use_primary:
        taken=min(math.ceil(n/2),len(P));out+=P[:taken]
    keys=[k for k in strata if not use_primary or k!=primary]
    keys.sort(key=lambda k:(h(f'{seed}#{k}'),k))
    lists=[strata[k] for k in keys]
    rnd=0
    while len(out)<n and any(rnd<len(l) for l in lists):
        for l in lists:
            if rnd<len(l) and len(out)<n:out.append(l[rnd])
        rnd+=1
    while len(out)<n and taken<len(P):out.append(P[taken]);taken+=1
    return sorted(out,key=lambda i:(hs[i],pool[i]))

def refs(t,k=10):return [f'{t}:{i}' for i in range(k)]
